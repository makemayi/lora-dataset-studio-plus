[CmdletBinding()]
param(
    [switch]$Configure,
    [string]$CandidatePath,
    [string]$OverridePath = '.docker-compose.external-comfy.override.yml'
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$utf8Strict = New-Object System.Text.UTF8Encoding($false, $true)
[Console]::OutputEncoding = $utf8NoBom
$schemaLine = '# lds-external-comfy-schema: 1'
$metadataPrefix = '# lds-external-comfy-path-base64: '

function Resolve-ComfyRoot {
    param([string]$LiteralPath)

    if ([string]::IsNullOrWhiteSpace($LiteralPath)) {
        return $null
    }
    if (-not [System.IO.Path]::IsPathRooted($LiteralPath)) {
        return $null
    }
    if ($LiteralPath.IndexOf([char]13) -ge 0 -or $LiteralPath.IndexOf([char]10) -ge 0) {
        return $null
    }

    $candidates = @($LiteralPath)
    if (Test-Path -LiteralPath $LiteralPath -PathType Container) {
        $candidates += (Join-Path $LiteralPath 'ComfyUI')
    }
    foreach ($candidate in $candidates) {
        if (-not (Test-Path -LiteralPath $candidate -PathType Container)) {
            continue
        }
        if (-not (Test-Path -LiteralPath (Join-Path $candidate 'main.py') -PathType Leaf)) {
            continue
        }
        if (-not (Test-Path -LiteralPath (Join-Path $candidate 'models') -PathType Container)) {
            continue
        }
        return (Resolve-Path -LiteralPath $candidate).ProviderPath
    }
    return $null
}

function New-OverlayText {
    param([string]$LiteralPath)

    $pathBytes = $utf8NoBom.GetBytes($LiteralPath)
    $encodedPath = [Convert]::ToBase64String($pathBytes)
    # Compose turns a doubled dollar back into one literal dollar. YAML single
    # quotes protect every other metacharacter; apostrophes are doubled.
    $dollar = [string][char]36
    $yamlPath = $LiteralPath.Replace($dollar, ($dollar + $dollar)).Replace("'", "''")
    $lines = @(
        $schemaLine
        ($metadataPrefix + $encodedPath)
        '# Generated by start-docker.bat. Use --configure instead of editing.'
        'services:'
        '  studio:'
        '    volumes:'
        '      - type: bind'
        ("        source: '" + $yamlPath + "'")
        '        target: /external-comfyui'
    )
    return (($lines -join [Environment]::NewLine) + [Environment]::NewLine)
}

function Read-ConfiguredPath {
    param([string]$FullOverridePath)

    $raw = [System.IO.File]::ReadAllText($FullOverridePath, $utf8Strict)
    $lines = [System.IO.File]::ReadAllLines($FullOverridePath, $utf8Strict)
    if ($lines.Count -lt 3 -or $lines[0] -cne $schemaLine) {
        throw 'Unsupported or missing override schema.'
    }
    if (-not $lines[1].StartsWith($metadataPrefix)) {
        throw 'Missing path metadata.'
    }
    $encodedPath = $lines[1].Substring($metadataPrefix.Length)
    if ($encodedPath -notmatch '^[A-Za-z0-9+/]+={0,2}$') {
        throw 'Invalid path metadata.'
    }
    $literalPath = $utf8Strict.GetString([Convert]::FromBase64String($encodedPath))
    $resolvedPath = Resolve-ComfyRoot -LiteralPath $literalPath
    if ($null -eq $resolvedPath -or $resolvedPath -cne $literalPath) {
        throw 'The configured ComfyUI folder is no longer valid.'
    }
    $expected = New-OverlayText -LiteralPath $literalPath
    if ($raw -cne $expected) {
        throw 'The generated override was modified.'
    }
    return $literalPath
}

$fullOverridePath = [System.IO.Path]::GetFullPath($OverridePath)

if (-not $Configure) {
    if (-not (Test-Path -LiteralPath $fullOverridePath -PathType Leaf)) {
        Write-Output 'STATE=ABSENT'
        exit 0
    }
    try {
        Read-ConfiguredPath -FullOverridePath $fullOverridePath | Out-Null
    }
    catch {
        Write-Output 'STATE=INVALID'
        exit 0
    }
    Write-Output 'STATE=VALID'
    exit 0
}

$selectedPath = $null
if ($PSBoundParameters.ContainsKey('CandidatePath')) {
    $selectedPath = Resolve-ComfyRoot -LiteralPath $CandidatePath
    if ($null -eq $selectedPath) {
        Write-Output 'STATE=INVALID'
        exit 0
    }
}
else {
    if ($env:LDS_TEST_CANCEL_FOLDER_PICKER) {
        Write-Output 'STATE=CANCELLED'
        exit 0
    }
    Add-Type -AssemblyName System.Windows.Forms
    $owner = New-Object System.Windows.Forms.Form
    $owner.ShowInTaskbar = $false
    $owner.TopMost = $true
    $owner.Opacity = 0
    $owner.Width = 1
    $owner.Height = 1
    $owner.StartPosition = [System.Windows.Forms.FormStartPosition]::CenterScreen
    $owner.Show()
    $owner.Activate()
    try {
        while ($null -eq $selectedPath) {
            $dialog = New-Object System.Windows.Forms.FolderBrowserDialog
            $dialog.Description = 'Select the folder containing main.py and models, or its portable parent folder.'
            $dialog.ShowNewFolderButton = $false
            $result = $dialog.ShowDialog($owner)
            $candidate = $dialog.SelectedPath
            $dialog.Dispose()

            if ($result -ne [System.Windows.Forms.DialogResult]::OK) {
                Write-Output 'STATE=CANCELLED'
                exit 0
            }
            $selectedPath = Resolve-ComfyRoot -LiteralPath $candidate
            if ($null -ne $selectedPath) {
                continue
            }
            [System.Windows.Forms.MessageBox]::Show(
                $owner,
                'Select the ComfyUI root containing main.py and models, or the portable parent that contains a ComfyUI folder.',
                'LoRA Dataset Studio',
                [System.Windows.Forms.MessageBoxButtons]::OK,
                [System.Windows.Forms.MessageBoxIcon]::Warning
            ) | Out-Null
        }
    }
    finally {
        $owner.Close()
        $owner.Dispose()
    }
}

$contents = New-OverlayText -LiteralPath $selectedPath
$directory = [System.IO.Path]::GetDirectoryName($fullOverridePath)
if (-not [string]::IsNullOrEmpty($directory)) {
    [System.IO.Directory]::CreateDirectory($directory) | Out-Null
}
$tempPath = $fullOverridePath + '.tmp'
try {
    [System.IO.File]::WriteAllText($tempPath, $contents, $utf8NoBom)
    if (Test-Path -LiteralPath $fullOverridePath -PathType Leaf) {
        [System.IO.File]::Replace($tempPath, $fullOverridePath, $null)
    }
    else {
        [System.IO.File]::Move($tempPath, $fullOverridePath)
    }
}
finally {
    if (Test-Path -LiteralPath $tempPath -PathType Leaf) {
        Remove-Item -LiteralPath $tempPath -Force -ErrorAction SilentlyContinue
    }
}

Write-Output 'STATE=SAVED'
